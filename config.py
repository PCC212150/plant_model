"""项目全局配置：目录路径与默认超参数。

所有可执行脚本（train/train.py、test/test.py、inference.py）都会加载本文件；
命令行参数会覆盖这里的默认值。部署到服务器（RTX 3090）时优先用
--size/--batch/--epochs 调整，无需改代码。

**本项目与 root_model 的关系**：两个平级项目，代码结构同构、部分模块逐字照抄
（照抄的在文件头注明了来源）。任务不同：
    root_model    俯拍近景 → 根系二/三通道分割 → 根数、根长
    plant_model   俯拍远景 → 茎/地上部/种茎三通道分割 → **株高**
"""
from pathlib import Path

# 项目根目录（本 config.py 所在目录）
PROJECT_ROOT = Path(__file__).resolve().parent

# ------------------------- 目录 -------------------------
DATASETS_DIR = PROJECT_ROOT / "datasets"
PLANT_DATA_DIR = DATASETS_DIR / "plant"   # 株高数据集根目录
MODEL_DIR = PROJECT_ROOT / "model"        # 模型根目录（内含 model_YYYYMMDDHHMM 子文件夹）
RESULT_DIR = PROJECT_ROOT / "result"      # 推理结果根目录

# 数据集布局：**扁平优先**（图片 / .json / .rsml 同层，当前数据集就是这样），
# 找不到再回退到 root_model 那种嵌套布局。两种都认，见 common/dataset.py 的 discover_pairs。
#   扁平：<data_dir>/*.jpg + *.json + *.rsml
#   嵌套：<data_dir>/images/*  + labels/roots/*.rsml + labels/other/*.json
IMAGES_SUBDIR = "images"
ROOTS_LABEL_SUBDIR = "labels/roots"
OTHER_LABEL_SUBDIR = "labels/other"

# ------------------------- 数据 -------------------------
IMAGE_EXTS = {".png", ".jpg", ".jpeg", ".bmp", ".tif", ".tiff"}

# 折线画掩码的线宽(px，原图尺度)。与 root_model 取同一个值，含义也一样：
# 真值线宽要和"模型该分割出来的东西"的宽度对齐 —— 太细等于让模型只学中心线，Dice 被白扣。
# **注意 root_model 有个坑别重犯**：那边 train 走 dataset 的默认值 5、test 用 config 的 10，
# 同一次实验训练与评测的真值线宽不一致。本项目**train/test 都显式传 config.MASK_LINE_WIDTH**。
MASK_LINE_WIDTH = 10

# 输入长边像素。训练用它；推理/测试**优先用模型训练时记录的 size**（从权重里读），
# 尺度必须与训练一致，否则精度明显下降。
#
# 与 root_model 的差别：那边的目标是**细根**（1024 下只有约 1.9px 宽），所以要往 1536/2048 顶；
# 本项目的三个目标里，`above`（地上部）是一大块区域、`sett`（种茎）是个小圆斑，
# 只有 `shoot`（茎）是细线（原图宽约 10px → 1024 下约 1.9px，与根同量级）。
# 所以 1024 起步够用，服务器上想再上一档就 --size 1536。
MAX_SIDE = 1024


# ---- 类别顺序 = 模型输出通道顺序 ----
# 三类不互斥（`shoot` 落在 `above` 里，`sett` 在 `shoot` 的起点端）：
#   shoot  rsml 的 1.1 —— 从「幼苗与种茎之间的基点」到「可见的叶鞘开口顶端」，
#          **它给出茎轴方向**，而株高就是沿这个方向量的（见下面的说明）
#   above  json 的 above_ground 矩形 —— 地上部范围
#   sett   json 的 stem polygon —— **种茎的横截面**（不是新茎！），
#          用来判定茎的哪一端是基部（离种茎近的那端）
CLASS_NAMES = ("shoot", "above", "sett")

# ------------------------- 株高的口径（全项目最重要的一条） -------------------------
# **株高 = 地上部沿「茎轴方向」的最大伸出量**（从基部起算）。
#
# 为什么不是"图像 x 跨度"或"图像竖直距离"：
#   植株是**平铺**拍的，站起来的高度 = 躺着时沿茎轴伸出多远。把植株放平时会绕茎轴滚一个
#   角度，叶片在**垂直于茎轴**方向的分量会被压掉，但**沿茎轴方向的分量是刚体旋转不变量**
#   —— 滚多少都不影响它。而 x 跨度里混进了茎本身倾斜的分量：实测茎翘 31.4° 时
#   x 跨度 1769 px，沿茎轴只有 1444 px，**偏大 22.5%**。
# 这条口径在 tool/measure_plant/measure_plant.py 里对**标注**实现过并验证，
# 本项目的 common/measure.py 对**预测掩码**实现同一套几何，两者必须给出同一个数。
#
# 代价：平放时叶片折返/堆叠会改变"最远点"落在哪，所以**摆放方式仍然影响结果** ——
# 这是采集端的问题，算法只能筛查（见 tool/measure_plant 的两个判据），不能修。

# 预测掩码二值化阈值。**不用 root_model 那套滞回低阈值**：那是为"细根断续"设计的，
# 本项目的 `above` 是块状区域，不存在断续问题；`shoot` 虽然细，但它只用来定方向，
# 断一小段不影响主轴。
PRED_THRESHOLD = 0.5

# 测量有效性兜底：预测出来的 `above` 像素数低于此值就当测量失败（记 measure_ok=否），
# 免得拿一个空掩码算出一个 0 还当成有效数据往下走。
MEASURE_MIN_ABOVE_PX = 500

# 长度单位换算：1 像素 = 多少毫米。0 = 只输出像素，不做换算。
# **目前没有已知尺寸的参照物**（刻度板的每格多少毫米是未知的），所以保持 0。
# 要填这个值只需一次标定：拍一张带尺子/硬币的图，量出它的像素宽度即可。
# 注意：不同批次的物距未必相同，跨批次比较前先用一张固定物体的图核对一遍。
MM_PER_PX = 0.0

# ------------------------- 损失权重 -------------------------
# 逐通道权重（顺序同 CLASS_NAMES）。三类都参与：株高靠 above，但没有 shoot 就没有茎轴方向，
# 没有 sett 就判不出基部在哪端 —— 三个都不能塌。
LOSS_BCE_W = (1.0, 1.0, 1.0)
LOSS_DICE_W = (1.0, 1.0, 1.0)
# 逐通道 BCE 的 pos_weight。shoot / sett 是小目标，正负比悬殊。**实测面积占比**
# （plant_C001-1_20241229CK，各分辨率下都量过）：
#     shoot  0.027% ~ 0.053%   ← 极细，且**线宽随分辨率变**：512/768 下只有 1px、
#                                1024 是 2px、1536 是 3px、2048 是 4px
#     sett   0.14%（各分辨率稳定，是个小圆斑）
#     above  19.3%（各分辨率稳定，大块区域）
# root_model 的经验是 0.8% 的通道取 10 能把目标"顶"出来又不至于糊成一片。
# 这里 shoot 比它小 20 倍，**10 大概率偏低** —— 真训起来必须扫（配合 Dice 看召回）。
# 若 shoot 的 Dice 卡住，按这个顺序试：① --size 上 1024/1536（先把线加宽）
# ② pos_weight 往上加 ③ MASK_LINE_WIDTH 加粗（见下面的说明）。
LOSS_POS_WEIGHT = (10.0, 1.0, 10.0)

# 折线画掩码的线宽**必须与分辨率配套看**：MASK_LINE_WIDTH=10 是「原图尺度」的宽度，
# 缩到模型分辨率后会变成 1~4px（见上表）。**shoot 通道的精度决定株高精度**
# （实测茎轴偏 5° 就 2.2% 误差，而掩码边界差 16px 才 0.65%）——
# 所以宁可把线画粗一点，也别让它细成 1px。
# 想加粗就改这个值（比如 20），但**train 与 test 必须用同一个值**，
# 且改了要重训（标签语义变了）。

# ------------------------- 数据增强（仅训练集） -------------------------
# 增强是抗过拟合与抗域偏移的主要手段。**注意本项目的翻转要小心**：
# 场景是有方向的（种茎永远在画面右侧、茎朝左），水平翻转会把方向翻过来，
# 虽然不影响分割质量，但会让 `sett 在右` 这类先验失效 —— 反正我们不用先验（基部由
# sett 掩码质心判定），所以翻转仍然允许。真正要防的是**尺度抖动过大会改变细茎的宽度**。
AUG_ROTATE_DEG = 20.0
AUG_SCALE = (0.8, 1.25)
AUG_SATURATION = (0.85, 1.15)
AUG_BRIGHTNESS = (0.85, 1.15)
AUG_CONTRAST = (0.85, 1.15)

# ------------------------- 训练超参 -------------------------
# 归一化类型："batch" 或 "group"。与 root_model 同样的结论：
# **本机 8G 只能用 batch** —— GroupNorm 多吃约 4GB 显存，一溢出就被丢到共享内存、慢 6~10 倍；
# 服务器（24G）上两者都行。BatchNorm 要求 batch≥2（batch=1 时每步只用单张图的统计量，
# 与推理用的滑动平均对不上，实测欠分割 3.5 倍），梯度累积救不了这个问题。
NORM = "batch"
BATCH_SIZE = 2            # BatchNorm 需要 batch≥2；本机 8G 在 1024 下够用
                          # 服务器（3090 24G）可 --batch 8 --size 1536
# 数据加载子进程数。0 = 主进程同步加载（Windows 默认，安全）；
# 服务器（Linux）设 4~8 让加载与训练并行，否则表现为「显存占满但 GPU-Util 接近 0」。
NUM_WORKERS = 0
ACCUM = 1                 # 梯度累积：显存不够又想要更大等效 batch 时用（救不了 batch=1 的 BatchNorm 问题）
EPOCHS = 5000             # 只是轮数上限；现在是 ReduceLROnPlateau，不拿它当退火周期
LR = 1e-3
WEIGHT_DECAY = 1e-4

# 学习率调度：验证 Dice 连续 LR_PATIENCE 轮不提升 → LR × LR_FACTOR（下限 MIN_LR）。
# root_model 曾用 CosineAnnealingLR(T_max=EPOCHS)，但早停总在一两百轮就结束，
# 余弦一次都没走到（实测全程恒定 1e-3），等于没退火。别再走回头路。
LR_PATIENCE = 25          # 必须 < PATIENCE：先降 LR，降完还不行才谈早停
LR_FACTOR = 0.5
MIN_LR = 1e-5
PATIENCE = 120            # 验证 Dice 连续 N 轮无提升则提前停止

# 验证集**植株数**：同一植株的所有时点整组进同一侧，避免同株泄漏。
# **当前只有 4 株**（C001-1 ~ C001-4），取 1 就是 1 株 / 2 张图 —— 少得只能验证流程通不通，
# 指标没有任何参考价值。等标注到 50~100 株再调这个值。
VAL_SIZE = 1
VAL_PLANTS = ()           # 非空则钉死验证植株（如 ("C001-3",)），VAL_SIZE 作回退
SEED = 42

# 模型输出分辨率与最长边相关的最小公倍数（U-Net 4 次下采样需能被 16 整除）
STRIDE = 16
